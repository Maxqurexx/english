"""Assemble data/words.js from the hand-written batches in content/*.txt.

Each batch line: rank | english | russian | association | example | example translation | icon
Lines starting with # are comments. Checks for duplicates, empty fields and
icon names missing from Tabler Icons (pass the icon CSS with --icons to check).

Usage: python tools/build_words.py [--icons path/to/tabler-icons.min.css]
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content"
OUT = ROOT / "data" / "words.js"

PSEUDOWORDS = [
    "blorrent", "trinch", "pellow", "skavish", "dorment", "framble", "quistle", "mundle",
    "crettle", "vorsh", "plinder", "glavish", "snorrow", "wembish", "throsk", "brintle",
    "clompet", "fendish", "harvel", "zaffer", "drimble", "stoven", "parlish", "grombe",
    "flessick", "yorrow", "swendle", "boskit", "tremish", "cullop",
]

icons = None
if "--icons" in sys.argv:
    css = Path(sys.argv[sys.argv.index("--icons") + 1]).read_text(encoding="utf-8")
    icons = set(re.findall(r"\.ti-([a-z0-9-]+):before", css))

# The frequency list decides the rank whenever the word is in it; the rank typed
# in a batch is only a fallback for base forms the list holds as inflections.
LIST_RANK = {}
wordlist = Path(__file__).with_name("wordlist.tsv")
if wordlist.exists():
    for line in wordlist.read_text(encoding="utf-8").splitlines():
        r, w = line.split("\t")
        LIST_RANK[w] = int(r)

rows, seen, problems = [], {}, []
used_ranks = {}
for path in sorted(CONTENT.glob("*.txt")):
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split("|")
        where = f"{path.name}:{n}"
        if len(parts) != 7 or not all(p.strip() for p in parts):
            problems.append(f"{where}: expected 7 non-empty fields, got {len(parts)}")
            continue
        rank, en, ru, assoc, ex, ex_ru, icon = (p.strip() for p in parts)
        if en.lower() in seen:
            problems.append(f"{where}: duplicate '{en}' (first at {seen[en.lower()]})")
            continue
        seen[en.lower()] = where
        if icons is not None and icon not in icons:
            problems.append(f"{where}: unknown icon '{icon}' for '{en}'")
            icon = "point"
        rank = LIST_RANK.get(en.lower(), int(rank))
        while rank in used_ranks:  # rank doubles as the word id, so keep it unique
            rank += 0.5 if isinstance(rank, int) else 0.25
        used_ranks[rank] = en
        rows.append([rank, en, ru, assoc, ex, ex_ru, icon])

rows.sort(key=lambda r: r[0])
js = (
    "// Generated by tools/build_words.py from content/*.tsv. Do not edit by hand.\n"
    "// Each row: [frequency rank, english, russian, association, example, example translation, icon].\n"
    f"window.WORDS_RAW = {json.dumps(rows, ensure_ascii=False, separators=(',', ':'))};\n"
    f"window.PSEUDOWORDS = {json.dumps(PSEUDOWORDS)};\n"
)
OUT.write_text(js, encoding="utf-8")
print(f"{len(rows)} words -> {OUT}")
for p in problems:
    print("WARN", p)
